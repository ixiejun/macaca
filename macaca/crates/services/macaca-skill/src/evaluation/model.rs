use serde::{Deserialize, Serialize};

/// Lifecycle state for a self-evolution evaluation run.
///
/// The state machine is intentionally small and generic. It lets a provider,
/// SDK client, or shell report whether baseline and evolved evidence have been
/// collected without embedding any application-specific workflow semantics.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum SelfEvolutionEvaluationLifecycle {
    /// The evaluation record exists but no comparable run has been recorded.
    Prepared,
    /// The baseline run was recorded with evolved skill state hidden or unused.
    BaselineRecorded,
    /// The evolved run was recorded with the promoted skill state available.
    EvolvedRecorded,
    /// The deterministic scoring policy produced a score for the record.
    Scored,
    /// White-box and black-box gates passed.
    Passed,
    /// A hard gate failed, such as missing activation or a policy regression.
    Failed,
    /// Evidence is insufficient to claim either success or failure.
    Inconclusive,
}

/// Provider-neutral evaluation record for a self-evolution measurement.
///
/// The record is a Command/State boundary object. It contains only identifiers,
/// refs, counts, and lifecycle state so Store/EventLog providers can replay the
/// measurement and shells can display it without receiving raw prompts,
/// provider payloads, package bytes, manifests, credentials, or full skill
/// instructions.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub struct SelfEvolutionEvaluationRecord {
    /// Stable id for this evaluation run, suitable for logs and report refs.
    pub evaluation_id: String,
    /// Trace id linking scoring, policy, audit, and report events.
    pub trace_id: String,
    /// Generic capability-shape id, never an application or business name.
    pub task_family_id: String,
    /// Current evaluation lifecycle state.
    pub lifecycle: SelfEvolutionEvaluationLifecycle,
    /// White-box evidence proving the governed evolution chain occurred.
    pub white_box: SelfEvolutionWhiteBoxEvidence,
    /// Metrics from the baseline task run.
    pub baseline: SelfEvolutionRunMetrics,
    /// Metrics from the task run that may use evolved skill state.
    pub evolved: SelfEvolutionRunMetrics,
    /// Durable report refs generated by the evaluation provider.
    pub report_refs: SelfEvolutionReportRefs,
}

/// Sanitized refs that prove the white-box self-evolution chain.
///
/// Every field is optional because the scoring policy must be able to explain
/// exactly which checkpoint is missing. Missing checkpoints are not silently
/// accepted; they become bounded failure or inconclusive reasons.
#[derive(Clone, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
pub struct SelfEvolutionWhiteBoxEvidence {
    /// Ref to verified terminal task success evidence from Task/Autonomy.
    pub verified_task_completion_ref: Option<String>,
    /// Ref to the bounded ExperienceCandidate derived from the completed task.
    pub experience_candidate_ref: Option<String>,
    /// Ref to the generic classification result.
    pub classification_ref: Option<String>,
    /// Draft or patch proposal id produced by Skill Evolution.
    pub proposal_id: Option<String>,
    /// Curation run id proving deterministic dry-run or apply participated.
    pub curation_run_id: Option<String>,
    /// Ref to approval, promotion, or apply evidence.
    pub promotion_or_apply_ref: Option<String>,
    /// Snapshot ref proving the evolved skill state became catalog-visible.
    pub active_catalog_snapshot_ref: Option<String>,
    /// Ref proving a later task read or activated the evolved skill.
    pub later_skill_activation_ref: Option<String>,
    /// Policy decision id when promotion, apply, rollback, or report access was gated.
    pub policy_decision_id: Option<String>,
    /// Sanitized audit event ids linked to this evaluation.
    pub audit_event_ids: Vec<String>,
    /// Snapshot ref captured before side-effecting evolution commands.
    pub before_snapshot_ref: Option<String>,
    /// Snapshot ref captured after promotion or apply.
    pub after_snapshot_ref: Option<String>,
    /// Rollback memento ref when the evaluated evolution can be reversed.
    pub rollback_ref: Option<String>,
}

/// White-box checkpoint category observed through service boundaries.
///
/// The enum is a Specification boundary for required self-evolution evidence.
/// It describes generic OS checkpoints only, never application workflows or
/// business-domain events.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum SelfEvolutionEvaluationCheckpointKind {
    /// Verified terminal task completion from Task/Autonomy evidence.
    VerifiedTaskCompletion,
    /// ExperienceCandidate derived from verified completion evidence.
    ExperienceCandidate,
    /// Generic classification result for the candidate.
    Classification,
    /// Draft or patch proposal created by skill evolution.
    Proposal,
    /// Curation dry-run or apply checkpoint.
    Curation,
    /// Approval, promotion, or apply decision.
    PromotionOrApply,
    /// Active catalog visibility snapshot.
    CatalogVisibility,
    /// Later read or activation of the evolved skill state.
    SkillActivation,
    /// Rejection evidence proving rejected proposals remain durable.
    Rejection,
    /// Rollback evidence proving memento restoration is available.
    Rollback,
}

/// Sanitized checkpoint append input for self-evolution evaluation.
///
/// The checkpoint carries refs and ids only. Providers must not place raw task
/// output, prompts, provider payloads, manifests, package bytes, credentials, or
/// full skill bodies in these fields; report builders still sanitize strings as
/// a defense-in-depth boundary before shell display.
#[derive(Clone, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
pub struct SelfEvolutionEvaluationCheckpoint {
    /// Generic checkpoint kind used by the append command to update evidence.
    pub kind: SelfEvolutionEvaluationCheckpointKind,
    /// Evidence ref for checkpoint kinds that map to one white-box evidence ref.
    pub evidence_ref: Option<String>,
    /// Proposal id when the checkpoint created or referenced a draft/patch.
    pub proposal_id: Option<String>,
    /// Curation run id when deterministic curation participated.
    pub curation_run_id: Option<String>,
    /// Policy decision id attached to this checkpoint, when policy ran.
    pub policy_decision_id: Option<String>,
    /// Sanitized audit event ids emitted for this checkpoint.
    pub audit_event_ids: Vec<String>,
    /// Memento ref captured before side effects.
    pub before_snapshot_ref: Option<String>,
    /// Memento ref captured after side effects.
    pub after_snapshot_ref: Option<String>,
    /// Rollback memento ref when the checkpoint can be reverted.
    pub rollback_ref: Option<String>,
}

impl Default for SelfEvolutionEvaluationCheckpointKind {
    fn default() -> Self {
        Self::VerifiedTaskCompletion
    }
}

impl SelfEvolutionWhiteBoxEvidence {
    /// Append one sanitized checkpoint into the white-box evidence chain.
    ///
    /// This is the Memento/Observer bridge for the evaluation harness: callers
    /// observe service-owned events and append refs here, while scoring remains
    /// deterministic over the resulting bounded record. The function never
    /// interprets application-specific behavior and never copies raw payloads.
    pub fn append_checkpoint(&mut self, checkpoint: &SelfEvolutionEvaluationCheckpoint) {
        match checkpoint.kind {
            SelfEvolutionEvaluationCheckpointKind::VerifiedTaskCompletion => {
                replace_if_present(
                    &mut self.verified_task_completion_ref,
                    &checkpoint.evidence_ref,
                );
            }
            SelfEvolutionEvaluationCheckpointKind::ExperienceCandidate => {
                replace_if_present(&mut self.experience_candidate_ref, &checkpoint.evidence_ref);
            }
            SelfEvolutionEvaluationCheckpointKind::Classification => {
                replace_if_present(&mut self.classification_ref, &checkpoint.evidence_ref);
            }
            SelfEvolutionEvaluationCheckpointKind::Proposal => {
                replace_if_present(&mut self.proposal_id, &checkpoint.proposal_id);
            }
            SelfEvolutionEvaluationCheckpointKind::Curation => {
                replace_if_present(&mut self.curation_run_id, &checkpoint.curation_run_id);
            }
            SelfEvolutionEvaluationCheckpointKind::PromotionOrApply => {
                replace_if_present(&mut self.promotion_or_apply_ref, &checkpoint.evidence_ref);
            }
            SelfEvolutionEvaluationCheckpointKind::CatalogVisibility => {
                replace_if_present(
                    &mut self.active_catalog_snapshot_ref,
                    &checkpoint.evidence_ref,
                );
            }
            SelfEvolutionEvaluationCheckpointKind::SkillActivation => {
                replace_if_present(
                    &mut self.later_skill_activation_ref,
                    &checkpoint.evidence_ref,
                );
            }
            SelfEvolutionEvaluationCheckpointKind::Rejection => {
                replace_if_present(&mut self.policy_decision_id, &checkpoint.policy_decision_id);
            }
            SelfEvolutionEvaluationCheckpointKind::Rollback => {
                replace_if_present(&mut self.rollback_ref, &checkpoint.rollback_ref);
            }
        }

        replace_if_present(&mut self.policy_decision_id, &checkpoint.policy_decision_id);
        replace_if_present(
            &mut self.before_snapshot_ref,
            &checkpoint.before_snapshot_ref,
        );
        replace_if_present(&mut self.after_snapshot_ref, &checkpoint.after_snapshot_ref);
        replace_if_present(&mut self.rollback_ref, &checkpoint.rollback_ref);
        self.audit_event_ids
            .extend(checkpoint.audit_event_ids.iter().cloned());
    }
}

fn replace_if_present(target: &mut Option<String>, value: &Option<String>) {
    if let Some(value) = value.as_ref().filter(|value| !value.trim().is_empty()) {
        *target = Some(value.clone());
    }
}

/// Comparable black-box task metrics for baseline and evolved runs.
///
/// Metrics are intentionally simple counts and durations. The scoring policy can
/// compare runs without reading task-specific payloads or branching on
/// application names, models, providers, drivers, gateways, chains, or business
/// domains.
#[derive(Clone, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
pub struct SelfEvolutionRunMetrics {
    /// Whether the run completed with verified terminal success.
    pub completion_success: bool,
    /// Count of durable artifacts, API checks, logs, or files that verify work.
    pub verified_artifact_count: u32,
    /// Count of human corrections, extra prompts, or manual interventions.
    pub human_intervention_count: u32,
    /// Wall-clock task duration when the runner can measure it.
    pub elapsed_seconds: Option<u64>,
    /// Count of tool calls used by the task runner.
    pub tool_call_count: u32,
    /// Count of failed attempts that required retry.
    pub retry_count: u32,
    /// Count of policy, audit, rollback, or sanitization violations.
    pub policy_violation_count: u32,
    /// Count of reads or activations of the evolved skill state.
    pub skill_activation_count: u32,
    /// Count of generated proposals that were accepted or promoted.
    pub accepted_proposal_count: u32,
    /// Count of total generated proposals considered by the evaluation.
    pub total_proposal_count: u32,
    /// Bounded generic reuse score across similar task-family runs.
    pub reuse_score: u32,
    /// Count of quality, behavior, or verification regressions.
    pub regression_count: u32,
}

/// Durable report references produced by an evaluation provider.
///
/// Reports are referenced, not embedded, so Store/EventLog can own retention and
/// shells can fetch sanitized summaries through SDK/SystemFacade readers.
#[derive(Clone, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
pub struct SelfEvolutionReportRefs {
    /// Ref to a sanitized machine-readable report.
    pub json_report_ref: Option<String>,
    /// Ref to a sanitized operator-readable report.
    pub markdown_report_ref: Option<String>,
}

/// Deterministic scoring output for an evaluation run.
///
/// Reasons are bounded strings selected by the scoring policy. They are suitable
/// for logs and reports because they describe missing refs or metric failures
/// without copying raw task output.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub struct SelfEvolutionScore {
    /// Final lifecycle state produced by scoring.
    pub lifecycle: SelfEvolutionEvaluationLifecycle,
    /// Whether all required gates passed.
    pub passed: bool,
    /// Bounded reason codes explaining failures or inconclusive evidence.
    pub reason_codes: Vec<String>,
}
